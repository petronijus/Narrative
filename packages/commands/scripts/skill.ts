/**
 * Generate the `narrative` Claude Code skill from the playbooks
 * (packages/commands/playbooks/*.md) — the same files the MCP server serves
 * as prompts, so the skill and the prompts never drift apart
 * (docs/plans/agentic-layer.md §4.4). Never edit the generated skill by hand.
 *
 * Usage:
 *   pnpm --filter @narrative/commands skill -- --out <skill dir> [--api-url <url>] [--check]
 *
 *   --out      the skill directory, e.g.
 *              <woodgrove-plugins>/plugins/narrative/skills/narrative
 *   --api-url  the public API base the setup section points at
 *              (default https://narrative.bastla.com/api)
 *   --check    write nothing; exit 1 when the directory is stale
 *
 * Output:
 *   SKILL.md               frontmatter (name, description written so Claude
 *                          Code picks the skill for Narrative work), setup,
 *                          the basics playbook, an index of the others
 *   references/<name>.md   every other playbook, placeholders shown as <arg>
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { rewriteCommandMentionsAsToolNames } from '../src/agentSurface.js'
import { BASICS_PLAYBOOK, loadPlaybooks, type Playbook } from '../src/playbooks/index.js'

const DEFAULT_API_URL = 'https://narrative.bastla.com/api'

const SKILL_DESCRIPTION =
  "Build, edit, restyle, shorten and translate presentations in Narrative, Woodgrove's collaborative deck editor, " +
  'through the Narrative MCP server (tools such as deck_list, query_deck, ops_apply). Use whenever the user ' +
  'mentions Narrative, a Narrative deck, slide or folder, narrative.bastla.com, or asks to change slides that ' +
  'live in Narrative — including "this slide" or "the selected text" in their open Narrative editor.'

function args(argv: string[]): { out: string; apiUrl: string; check: boolean } {
  const rest = argv.filter((a) => a !== '--')
  const value = (flag: string): string | undefined => {
    const i = rest.indexOf(flag)
    return i >= 0 ? rest[i + 1] : undefined
  }
  const out = value('--out')
  if (out === undefined || out.startsWith('--')) {
    console.error(
      'usage: pnpm --filter @narrative/commands skill -- --out <skill dir> [--api-url <url>] [--check]',
    )
    process.exit(2)
  }
  return {
    out: path.resolve(out),
    apiUrl: (value('--api-url') ?? DEFAULT_API_URL).replace(/\/+$/, ''),
    check: rest.includes('--check'),
  }
}

/** Playbook prose for the skill: tool names, and `{{arg}}` shown as `<arg>`. */
function forSkill(text: string): string {
  return rewriteCommandMentionsAsToolNames(text).replace(/\{\{\s*([A-Za-z0-9]+)\s*\}\}/g, '<$1>')
}

const GENERATED =
  '<!-- Generated by `pnpm --filter @narrative/commands skill` from packages/commands/playbooks in the Narrative repo. Do not edit by hand: change the playbook and regenerate. -->'

function referenceFile(p: Playbook): string {
  const inputs =
    p.arguments.length === 0
      ? ''
      : [
          '## Inputs',
          '',
          "Take these from the user's request (ask if a required one is missing):",
          '',
          ...p.arguments.map(
            (a) =>
              `- \`<${a.name}>\`${a.required ? ' (required)' : ''}: ${a.description}` +
              (a.default === undefined ? '' : ` Default: ${a.default}.`),
          ),
          '',
        ].join('\n')
  return [
    GENERATED,
    '',
    `# ${p.title}`,
    '',
    `${p.description}`,
    '',
    inputs,
    forSkill(p.body),
    '',
  ].join('\n')
}

function skillFile(playbooks: Playbook[], apiUrl: string): string {
  const basics = playbooks.find((p) => p.name === BASICS_PLAYBOOK)!
  const others = playbooks.filter((p) => p.name !== BASICS_PLAYBOOK)
  return [
    '---',
    'name: narrative',
    `description: ${JSON.stringify(SKILL_DESCRIPTION)}`,
    '---',
    '',
    GENERATED,
    '',
    '# Narrative',
    '',
    "Narrative is Woodgrove's collaborative presentation editor. You drive it through the tools of the",
    '`narrative` MCP server (in Claude Code they are named `mcp__narrative__<tool>`, e.g.',
    '`mcp__narrative__query_deck`). Every tool is a Narrative command acting as the signed-in user.',
    '',
    '## Setup (once per machine)',
    '',
    '1. In Narrative, open the account menu → **Access tokens** and create a token with the `mcp` scope.',
    '2. Register the server for your user:',
    '',
    '   ```bash',
    `   claude mcp add --transport http --scope user narrative ${apiUrl}/mcp --header "Authorization: Bearer <token>"`,
    '   ```',
    '',
    '3. Check it with `claude mcp list` (it should say "connected"). If the tools are missing, the token is',
    '   wrong, expired or revoked: create a new one. claude.ai users add Narrative as a custom connector',
    `   (\`${apiUrl}/mcp\`) and sign in with Google instead of using a token.`,
    '',
    '## Playbooks',
    '',
    'Read the matching playbook before you start a task; they build on the basics below.',
    '',
    ...others.map(
      (p) =>
        `- **${p.title}** — ${p.description} → [references/${p.name}.md](references/${p.name}.md)`,
    ),
    '',
    `# ${basics.title}`,
    '',
    forSkill(basics.body),
    '',
  ].join('\n')
}

function expectedFiles(out: string, apiUrl: string): Map<string, string> {
  const playbooks = loadPlaybooks()
  const files = new Map<string, string>([
    [path.join(out, 'SKILL.md'), skillFile(playbooks, apiUrl)],
  ])
  for (const p of playbooks.filter((x) => x.name !== BASICS_PLAYBOOK))
    files.set(path.join(out, 'references', `${p.name}.md`), referenceFile(p))
  return files
}

const { out, apiUrl, check } = args(process.argv.slice(2))
const files = expectedFiles(out, apiUrl)
const referencesDir = path.join(out, 'references')
const orphans = existsSync(referencesDir)
  ? readdirSync(referencesDir)
      .map((f) => path.join(referencesDir, f))
      .filter((f) => !files.has(f))
  : []

let stale = false
for (const [file, content] of files) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null
  if (current === content) continue
  if (check) {
    console.error(`stale: ${file}`)
    stale = true
    continue
  }
  mkdirSync(path.dirname(file), { recursive: true })
  writeFileSync(file, content)
  console.log(`wrote ${file}`)
}
for (const orphan of orphans) {
  // A playbook was removed or renamed. Never delete here: say so, and let a
  // person move the file to the trash.
  console.error(`no longer generated (remove it): ${orphan}`)
  stale = true
}
if (check && stale) {
  console.error(
    'The narrative skill is stale: run `pnpm --filter @narrative/commands skill -- --out <dir>`.',
  )
  process.exit(1)
}
if (!check && orphans.length > 0) process.exit(1)
