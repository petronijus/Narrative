/**
 * The generated `narrative` Claude Code skill: which files it consists of and
 * their exact content. Shared by the generator CLI (scripts/skill.ts) and the
 * freshness test (scripts/skill.test.ts) so both agree byte for byte.
 *
 * The skill lives IN THIS REPO, in the Claude Code plugin at
 * `claude-plugin/narrative/` (installed with
 * `/plugin marketplace add petronijus/Narrative`, see the root
 * `.claude-plugin/marketplace.json`). Content is run through Prettier with
 * the repo config, because the pre-commit hook formats every staged `.md`.
 *
 * The plugin manifest (`claude-plugin/narrative/.claude-plugin/plugin.json`)
 * is generated too, with the Narrative release as its version: Claude Code
 * only fetches a plugin again when its version changes, so a manifest stuck
 * at one version kept every installed skill at whatever it was first
 * installed with. Every release bumps the version, the freshness test
 * (skill.test.ts) then fails until the skill is regenerated, and
 * `/plugin update narrative` brings the new skill.
 */

import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'
import { rewriteCommandMentionsAsToolNames } from '../src/agentSurface.js'
import { BASICS_PLAYBOOK, loadPlaybooks, type Playbook } from '../src/playbooks/index.js'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')

/** Where the skill is generated: the plugin shipped from this repo. */
export const DEFAULT_SKILL_DIR = path.join(
  repoRoot,
  'claude-plugin',
  'narrative',
  'skills',
  'narrative',
)

export const DEFAULT_API_URL = 'https://narrative.bastla.com/api'

/** The plugin's manifest, next to the default skill directory. */
export const PLUGIN_MANIFEST = path.join(
  repoRoot,
  'claude-plugin',
  'narrative',
  '.claude-plugin',
  'plugin.json',
)

/** The Narrative release (the root package.json, which every release bumps with the rest). */
function narrativeVersion(): string {
  const pkg = JSON.parse(readFileSync(path.join(repoRoot, 'package.json'), 'utf8')) as {
    version?: unknown
  }
  if (typeof pkg.version !== 'string') throw new Error('package.json has no version')
  return pkg.version
}

function pluginManifest(): string {
  return JSON.stringify({
    name: 'narrative',
    version: narrativeVersion(),
    description:
      "Drive Narrative, Woodgrove's collaborative presentation editor, from Claude Code: the narrative skill " +
      'teaches Claude how to read, edit, restyle, shorten and translate decks through the Narrative MCP server.',
    author: { name: 'Woodgrove Digital' },
    keywords: ['narrative', 'presentations', 'decks', 'mcp', 'slides'],
  })
}

const SKILL_DESCRIPTION =
  "Build, edit, restyle, shorten and translate presentations in Narrative, Woodgrove's collaborative deck editor, " +
  'through the Narrative MCP server (tools such as deck_list, query_deck, ops_apply). Use whenever the user ' +
  'mentions Narrative, a Narrative deck, slide or folder, narrative.bastla.com, or asks to change slides that ' +
  'live in Narrative — including "this slide" or "the selected text" in their open Narrative editor.'

/** Playbook prose for the skill: tool names, and `{{arg}}` shown as `<arg>`. */
function forSkill(text: string): string {
  return rewriteCommandMentionsAsToolNames(text).replace(/\{\{\s*([A-Za-z0-9]+)\s*\}\}/g, '<$1>')
}

const GENERATED =
  '<!-- Generated by `pnpm --filter @narrative/commands skill` from packages/commands/playbooks in the Narrative repo. Do not edit by hand: change the playbook and regenerate. -->'

function referenceFile(p: Playbook): string {
  const inputs =
    p.arguments.length === 0
      ? ''
      : [
          '## Inputs',
          '',
          "Take these from the user's request (ask if a required one is missing):",
          '',
          ...p.arguments.map(
            (a) =>
              `- \`<${a.name}>\`${a.required ? ' (required)' : ''}: ${a.description}` +
              (a.default === undefined ? '' : ` Default: ${a.default}.`),
          ),
          '',
        ].join('\n')
  return [
    GENERATED,
    '',
    `# ${p.title}`,
    '',
    `${p.description}`,
    '',
    inputs,
    forSkill(p.body),
    '',
  ].join('\n')
}

function skillFile(playbooks: Playbook[], apiUrl: string): string {
  const basics = playbooks.find((p) => p.name === BASICS_PLAYBOOK)!
  const others = playbooks.filter((p) => p.name !== BASICS_PLAYBOOK)
  return [
    '---',
    'name: narrative',
    `description: ${JSON.stringify(SKILL_DESCRIPTION)}`,
    '---',
    '',
    GENERATED,
    '',
    '# Narrative',
    '',
    "Narrative is Woodgrove's collaborative presentation editor. You drive it through the tools of the",
    '`narrative` MCP server (in Claude Code they are named `mcp__narrative__<tool>`, e.g.',
    '`mcp__narrative__query_deck`). Every tool is a Narrative command acting as the signed-in user.',
    '',
    '## Setup (once per machine)',
    '',
    '1. In Narrative, open the account menu → **Access tokens** and create a token with the `mcp` scope.',
    '2. Register the server for your user:',
    '',
    '   ```bash',
    `   claude mcp add --transport http --scope user narrative ${apiUrl}/mcp --header "Authorization: Bearer <token>"`,
    '   ```',
    '',
    '3. Check it with `claude mcp list` (it should say "connected"). If the tools are missing, the token is',
    '   wrong, expired or revoked: create a new one. claude.ai users add Narrative as a custom connector',
    `   (\`${apiUrl}/mcp\`) and sign in with Google instead of using a token.`,
    '',
    '## Playbooks',
    '',
    'Read the matching playbook before you start a task; they build on the basics below.',
    '',
    ...others.map(
      (p) =>
        `- **${p.title}** — ${p.description} → [references/${p.name}.md](references/${p.name}.md)`,
    ),
    '',
    `# ${basics.title}`,
    '',
    forSkill(basics.body),
    '',
  ].join('\n')
}

function rawFiles(out: string, apiUrl: string): Map<string, string> {
  const playbooks = loadPlaybooks()
  const files = new Map<string, string>([
    [path.join(out, 'SKILL.md'), skillFile(playbooks, apiUrl)],
  ])
  for (const p of playbooks.filter((x) => x.name !== BASICS_PLAYBOOK))
    files.set(path.join(out, 'references', `${p.name}.md`), referenceFile(p))
  // The manifest belongs to the plugin in this repo, not to a skill written elsewhere.
  if (path.resolve(out) === DEFAULT_SKILL_DIR) files.set(PLUGIN_MANIFEST, pluginManifest())
  return files
}

/** The skill's files (absolute path → formatted content). */
export async function skillFiles(
  out: string = DEFAULT_SKILL_DIR,
  apiUrl: string = DEFAULT_API_URL,
): Promise<Map<string, string>> {
  const formatted = new Map<string, string>()
  for (const [file, raw] of rawFiles(out, apiUrl)) {
    const config = (await prettier.resolveConfig(file)) ?? {}
    formatted.set(file, await prettier.format(raw, { ...config, filepath: file }))
  }
  return formatted
}
