/**
 * commands/src/batchForks.test.ts — atomic batches on a kept fork
 * (batchForks.ts): the same all-or-nothing results as a one-off copy,
 * edits made between batches seen, a failed batch leaving nothing behind,
 * no client id per batch, and the fork let go when it should be.
 */

import { afterEach, describe, expect, it, vi } from 'vitest'
import * as Y from 'yjs'
import {
  LOCAL_ORIGIN,
  agentOrigin,
  createUndoManager,
  getSlideObjectsCtx,
  listSlides,
  removeObject,
  setSlideName,
} from '@narrative/slide-model'
import { BatchForks } from './batchForks.js'
import { createDefaultRegistry } from './catalog.js'
import { CommandError } from './errors.js'
import { runBatch } from './run.js'
import { createFixtureDeck } from './testing/fixtureDeck.js'
import type { CommandContext, CommandInvocation } from './types.js'

const registry = createDefaultRegistry()

function ctxWith(forks: BatchForks | undefined, deck = createFixtureDeck()): CommandContext {
  return {
    actor: { userId: 'u1', role: 'editor', kind: 'agent' },
    host: 'server',
    origin: agentOrigin('run-forks'),
    deck,
    ...(forks === undefined ? {} : { batchForks: forks }),
  }
}

const plain = (ctx: CommandContext): unknown => JSON.parse(JSON.stringify(listSlides(ctx.deck!)))
const clients = (doc: Y.Doc): number => Y.decodeStateVector(Y.encodeStateVector(doc)).size

const move = (objects: string[], dx = 5): CommandInvocation => ({
  command: 'object.move',
  input: { slide: 's1', objects, dx, dy: 0 },
})

function codeOf(fn: () => unknown): string | undefined {
  try {
    fn()
  } catch (e) {
    return e instanceof CommandError ? e.code : String(e)
  }
  return undefined
}

let forks: BatchForks
afterEach(() => forks?.close())

describe('BatchForks', () => {
  it('keeps one fork per document and sees edits made between batches', () => {
    forks = new BatchForks()
    const ctx = ctxWith(forks)
    runBatch(registry, ctx, [{ command: 'slide.add', input: {} }])
    expect(forks.size).toBe(1)
    // Between batches the live document changes outside any batch…
    setSlideName(ctx.deck!, 's2', 'Renamed live')
    removeObject(getSlideObjectsCtx(ctx.deck!, 's1')!, 'e1')
    // …and the next batch works on that state: e1 is gone, s2 renamed.
    expect(codeOf(() => runBatch(registry, ctx, [move(['e1'])]))).toBe('not_found')
    const { results } = runBatch(registry, ctx, [
      { command: 'slide.rename', input: { slide: 's2', name: 'Renamed in a batch' } },
      move(['r1']),
    ])
    expect(results).toHaveLength(2)
    expect(listSlides(ctx.deck!).find((s) => s.id === 's2')!.name).toBe('Renamed in a batch')
  })

  it('gives the same document as a one-off copy per batch, over a run of batches and live edits', () => {
    forks = new BatchForks()
    const kept = ctxWith(forks)
    const oneOff = ctxWith(undefined)
    const steps: Array<(ctx: CommandContext) => void> = [
      (c) => runBatch(registry, c, [{ command: 'slide.add', input: {} }, move(['r1', 'e1'])]),
      (c) => setSlideName(c.deck!, 's1', 'Live'),
      (c) =>
        runBatch(registry, c, [
          { command: 'object.duplicate', input: { slide: 's1', objects: ['r1'] } },
        ]),
      (c) => {
        // A failing batch: nothing of it may remain.
        expect(codeOf(() => runBatch(registry, c, [move(['r1']), move(['nope'])]))).toBe(
          'not_found',
        )
      },
      (c) => removeObject(getSlideObjectsCtx(c.deck!, 's1')!, 't1'),
      (c) => runBatch(registry, c, [move(['img1'], -20), { command: 'slide.add', input: {} }]),
    ]
    for (const step of steps) {
      step(kept)
      step(oneOff)
    }
    // Structural comparison (ids generated by the ops differ between the two).
    const shape = (c: CommandContext) =>
      listSlides(c.deck!).map((s) => ({
        name: s.name,
        objects: s.objects.map((o) => ({ type: o.type, x: o.x, y: o.y })),
      }))
    expect(shape(kept)).toEqual(shape(oneOff))
  })

  it('leaves the live document untouched by a failed batch and lets the fork go', () => {
    forks = new BatchForks()
    const ctx = ctxWith(forks)
    runBatch(registry, ctx, [move(['r1'])])
    const before = plain(ctx)
    const sv = Y.encodeStateVector(ctx.deck!.doc)
    const updates: Uint8Array[] = []
    ctx.deck!.doc.on('update', (u: Uint8Array) => updates.push(u))
    expect(codeOf(() => runBatch(registry, ctx, [move(['r1']), move(['missing'])]))).toBe(
      'not_found',
    )
    expect(updates).toHaveLength(0)
    expect(Y.encodeStateVector(ctx.deck!.doc)).toEqual(sv)
    expect(plain(ctx)).toEqual(before)
    expect(forks.size).toBe(0)
    // The next batch makes a new fork and applies normally.
    runBatch(registry, ctx, [move(['r1'])])
    expect(forks.size).toBe(1)
    expect(updates).toHaveLength(1)
  })

  it('adds one client to the document for the life of a fork, not one per batch', () => {
    forks = new BatchForks()
    const ctx = ctxWith(forks)
    const live = ctx.deck!.doc
    const id = live.clientID
    const start = clients(live)
    for (let i = 0; i < 5; i++) runBatch(registry, ctx, [move(['r1'])])
    expect(clients(live)).toBe(start + 1)
    expect(live.clientID).toBe(id)
  })

  it('a one-off fork never borrows the live client id, which Yjs would re-roll', () => {
    const ctx = ctxWith(undefined)
    const live = ctx.deck!.doc
    // The live document has written under its own id: a copy under that id
    // would be given a random one by Yjs (with a console warning).
    setSlideName(ctx.deck!, 's1', 'Written live')
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => undefined)
    const log = vi.spyOn(console, 'log').mockImplementation(() => undefined)
    const error = vi.spyOn(console, 'error').mockImplementation(() => undefined)
    const id = live.clientID
    const updates: Uint8Array[] = []
    live.on('update', (u: Uint8Array) => updates.push(u))
    try {
      runBatch(registry, ctx, [move(['r1'])])
      const said = [...warn.mock.calls, ...log.mock.calls, ...error.mock.calls].flat().join(' ')
      expect(said).not.toContain('client-id')
    } finally {
      warn.mockRestore()
      log.mockRestore()
      error.mockRestore()
    }
    expect(live.clientID).toBe(id)
    const writers = new Set(Y.decodeUpdate(updates[0]!).structs.map((s) => s.id.client))
    expect(writers.size).toBe(1)
    expect(writers.has(id)).toBe(false)
  })

  it('forks the document as it is when the batch runs inside a transaction that already changed it', () => {
    forks = new BatchForks()
    const ctx = ctxWith(forks)
    runBatch(registry, ctx, [move(['r1'])])
    let refused: string | undefined
    ctx.deck!.doc.transact(() => {
      // Deleted in the same, still open, transaction: in no update yet.
      removeObject(getSlideObjectsCtx(ctx.deck!, 's1')!, 'e1')
      refused = codeOf(() => runBatch(registry, ctx, [move(['e1'])]))
    }, ctx.origin)
    expect(refused).toBe('not_found')
    // The kept fork caught up with the transaction afterwards.
    expect(codeOf(() => runBatch(registry, ctx, [move(['e1'])]))).toBe('not_found')
    expect(codeOf(() => runBatch(registry, ctx, [move(['r1'])]))).toBeUndefined()
  })

  it('is one undo step and one update for a collaborator', () => {
    forks = new BatchForks()
    const ctx = ctxWith(forks)
    const local = { ...ctx, origin: LOCAL_ORIGIN }
    const undo = createUndoManager(local.deck!)
    const peer = new Y.Doc()
    Y.applyUpdate(peer, Y.encodeStateAsUpdate(local.deck!.doc))
    const received: Uint8Array[] = []
    local.deck!.doc.on('update', (u: Uint8Array) => {
      received.push(u)
      Y.applyUpdate(peer, u)
    })
    runBatch(registry, local, [move(['r1'])]) // makes the fork
    undo.stopCapturing() // the next batch is its own step, not merged by time
    const before = plain(local)
    runBatch(registry, local, [
      { command: 'slide.add', input: {} },
      { command: 'slide.rename', input: { slide: { index: 3 }, name: 'Kept fork' } },
    ])
    expect(received).toHaveLength(2)
    expect(listSlides({ doc: peer, slides: peer.getArray('slides') })[3]!.name).toBe('Kept fork')
    undo.undo()
    expect(plain(local)).toEqual(before)
  })

  it('lets a fork go after its idle time, with its document, and past the size caps', () => {
    vi.useFakeTimers()
    try {
      forks = new BatchForks({ idleMs: 1000, maxForks: 2, maxPendingBytes: 64 })
      const a = ctxWith(forks)
      runBatch(registry, a, [move(['r1'])])
      expect(forks.size).toBe(1)
      vi.advanceTimersByTime(1001)
      expect(forks.size).toBe(0)

      runBatch(registry, a, [move(['r1'])])
      // Live edits beyond maxPendingBytes: replaying would cost more than a copy.
      for (let i = 0; i < 20; i++) setSlideName(a.deck!, 's1', `name ${i} `.repeat(4))
      expect(forks.size).toBe(0)

      const b = ctxWith(forks)
      const c = ctxWith(forks)
      runBatch(registry, a, [move(['r1'])])
      runBatch(registry, b, [move(['r1'])])
      runBatch(registry, c, [move(['r1'])])
      expect(forks.size).toBe(2)

      c.deck!.doc.destroy()
      expect(forks.size).toBe(1)
    } finally {
      vi.useRealTimers()
    }
  })
})
