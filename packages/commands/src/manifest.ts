/**
 * commands/src/manifest.ts
 *
 * The capability manifest: a deterministic description of every command
 * (plus what is still known-missing and what is deliberately excluded).
 * Input/output JSON Schemas are deliberately NOT part of it: they are
 * derived from the zod schemas in code (reviewed there) and hosts such as
 * the MCP server generate them at runtime; committing them would bury
 * capability changes under hundreds of KB of schema churn.
 *
 * Committed as packages/commands/capabilities.json and docs/capabilities.md
 * so every change to the agent surface shows up in the diff Petr reads; a
 * test fails when the committed copies are stale.
 */

import type { CommandRegistry } from './registry.js'
import type { RouteRef } from './types.js'
import { KNOWN_MISSING, type KnownMissing } from './parity/knownMissing.js'
import { AGENT_ALLOWLIST, type AllowlistEntry } from './parity/allowlist.js'

export interface CapabilityEntry {
  id: string
  domain: string
  title: string
  description: string
  role: string
  effects: string[]
  undo: string
  confirm: string
  hosts: string[]
  /** API routes the command is the agent-facing equivalent of (only present when it wraps any). */
  routes?: RouteRef[]
}

export interface CapabilityManifest {
  commands: CapabilityEntry[]
  knownMissing: KnownMissing[]
  allowlist: AllowlistEntry[]
}

export function buildManifest(registry: CommandRegistry): CapabilityManifest {
  return {
    commands: registry.list().map((def) => ({
      id: def.id,
      domain: def.domain,
      title: def.title,
      description: def.description,
      role: def.role,
      effects: [...def.effects],
      undo: def.undo,
      confirm: def.confirm,
      hosts: [...def.hosts],
      ...(def.routes !== undefined && def.routes.length > 0 ? { routes: [...def.routes] } : {}),
    })),
    knownMissing: [...KNOWN_MISSING],
    allowlist: [...AGENT_ALLOWLIST],
  }
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

function routeList(routes: readonly RouteRef[] | undefined): string {
  return (routes ?? []).map((r) => `\`${r.method} ${r.path}\``).join(', ')
}

export function renderManifestMarkdown(manifest: CapabilityManifest): string {
  const lines: string[] = [
    '# Capabilities',
    '',
    '> Generated by `pnpm --filter @narrative/commands capabilities` from the command',
    '> registry in `packages/commands`. Do not edit by hand — a test fails when this',
    '> file is stale. See ADR 0010 and `docs/plans/agentic-layer.md`.',
    '',
    `Commands: **${manifest.commands.length}**. Known missing: **${manifest.knownMissing.length}**. ` +
      `Deliberately excluded: **${manifest.allowlist.length}**.`,
    '',
  ]
  const domains = [...new Set(manifest.commands.map((c) => c.domain))].sort()
  for (const domain of domains) {
    lines.push(
      `## ${domain}`,
      '',
      '| Command | What it does | Role | Undo | Confirm |',
      '| --- | --- | --- | --- | --- |',
    )
    for (const c of manifest.commands.filter((x) => x.domain === domain)) {
      lines.push(`| \`${c.id}\` | ${cell(c.title)} | ${c.role} | ${c.undo} | ${c.confirm} |`)
    }
    lines.push('')
  }
  lines.push(
    '## Known missing',
    '',
    '| Capability | Phase | Today in | Note |',
    '| --- | --- | --- | --- |',
  )
  for (const m of manifest.knownMissing) {
    const today =
      [m.where ?? '', routeList(m.routes)].filter((x) => x !== '').join('; ') || m.source
    lines.push(`| \`${m.capability}\` | ${m.phase} | ${cell(today)} | ${cell(m.note ?? '')} |`)
  }
  lines.push(
    '',
    '## Deliberately excluded',
    '',
    '| Capability | Routes | Reason |',
    '| --- | --- | --- |',
  )
  for (const a of manifest.allowlist)
    lines.push(`| ${cell(a.capability)} | ${cell(routeList(a.routes))} | ${cell(a.reason)} |`)
  lines.push('')
  return lines.join('\n')
}
